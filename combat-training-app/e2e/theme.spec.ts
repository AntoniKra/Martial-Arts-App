import { test, expect } from './fixtures'

const groupName = 'Motyw'
test('remembers explicit choices and follows live system changes only in system mode', async ({ app, page }) => {
  await app.open('/profile')
  const group = page.getByRole('radiogroup', { name: groupName, exact: true })
  await expect(group.getByRole('radio', { name: 'Systemowy', exact: true })).toBeChecked()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await group.getByRole('radio', { name: 'Jasny', exact: true }).click()
  await page.reload()
  await expect(group.getByRole('radio', { name: 'Jasny', exact: true })).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await group.getByRole('radio', { name: 'Ciemny', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await page.reload()
  await expect(group.getByRole('radio', { name: 'Ciemny', exact: true })).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await group.getByRole('radio', { name: 'Systemowy', exact: true }).click()
  await page.reload()
  await expect(group.getByRole('radio', { name: 'Systemowy', exact: true })).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})
