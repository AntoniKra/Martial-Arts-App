import AxeBuilder from '@axe-core/playwright'
import { test, expect, openProfile, expandProfileSection } from './fixtures'
import { createVerifiedAccount, signIn, signInWithFakeGoogle, testPassword, uniqueEmail } from './authEmulator'
import { workoutSession } from '../src/test/workoutSessionBuilders'

for (const theme of ['dark', 'light'] as const) {
  test(`orders profile settings and collapses cards with accessible controls in ${theme}`, async ({ app, page }) => {
    await app.open('/profile')
    await app.setTheme(theme)
    await app.seedSession(workoutSession({ workoutDate: '2026-11-13', durationSeconds: 3600 }))
    await expect(page.getByRole('main').getByRole('heading').filter({ hasText: /^(Profil|Masa ciała|Samopoczucie|Statystyki|Ustawienia|Trening|Zdrowie i zgody|Wygląd|Twoje dane|Konto|Usuń konto)/ }))
      .toHaveText(['Profil', /^Masa ciała/, /^Samopoczucie/, /^Statystyki/, 'Ustawienia', 'Trening', 'Zdrowie i zgody', 'Wygląd', 'Twoje dane', 'Konto', 'Usuń konto'])
    for (const name of ['Masa ciała', 'Samopoczucie', 'Statystyki']) {
      await expect(page.getByRole('region', { name, exact: true }).getByRole('button').first()).toHaveAttribute('aria-expanded', 'false')
    }
    await expect(page.getByRole('region', { name: 'Statystyki', exact: true })).toContainText('1 trening')
    await expect(page.getByRole('definition')).toHaveCount(0)
    await expect(page.getByRole('img')).toHaveCount(0)
    await expect(page.getByRole('link', { name: 'Włącz zapisywanie masy ciała', exact: true })).toHaveCount(0)
    await expect(page.getByRole('link', { name: 'Włącz Samopoczucie', exact: true })).toHaveCount(0)
    await expect(page.locator('header')).toContainText('Hasło')
    await expect(page.locator('header').getByRole('button')).toHaveCount(0)
    await expect(page.getByRole('navigation').getByRole('button', { name: /motyw|Wyloguj/i })).toHaveCount(0)
    const training = page.getByRole('region', { name: 'Trening', exact: true })
    await expect(training.getByRole('radiogroup', { name: 'Sygnał przed końcem rundy', exact: true }).getByRole('radio', { name: '10 s', exact: true })).toBeChecked()
    await expect(training.getByRole('radiogroup', { name: 'Sygnał przed końcem przerwy', exact: true }).getByRole('radio', { name: '10 s', exact: true })).toBeChecked()
    await page.evaluate(() => { scrollTo(0, 0); return document.fonts.ready })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) => impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])
    for (const name of ['Masa ciała', 'Samopoczucie', 'Statystyki']) await expandProfileSection(page, name)
    await expect(page.getByRole('definition').first()).toHaveText('1')
    await expect(page.getByRole('link', { name: 'Włącz zapisywanie masy ciała', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Włącz Samopoczucie', exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('button', { name: /^Masa ciała/ })).toHaveAttribute('aria-expanded', 'false')
    await page.getByRole('link', { name: 'Zgoda: masa ciała', exact: true }).click()
    await expect(page.getByRole('button', { name: /^Masa ciała/ })).toHaveAttribute('aria-expanded', 'true')
    await page.getByRole('link', { name: 'Start', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Wyloguj', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: /Włącz (jasny|ciemny) motyw/ })).toHaveCount(0)
  })
}

test('validates password changes, reauthenticates on the emulator and signs out from Profile', async ({ page, request }) => {
  const account = await createVerifiedAccount(request)
  await page.goto('/login')
  await signIn(page, account)
  await openProfile(page)
  const submit = page.getByRole('button', { name: 'Zmień hasło', exact: true })
  await submit.click()
  await expect(page.getByLabel('Obecne hasło', { exact: true })).toBeFocused()
  await expect(page.getByText('Wpisz obecne hasło.', { exact: true })).toBeVisible()
  await page.getByLabel('Obecne hasło', { exact: true }).fill('wrong-test-only')
  await page.getByLabel('Nowe hasło', { exact: true }).fill('Updated-test-only-2026')
  await submit.click()
  await expect(page.getByRole('alert')).toHaveText('Obecne hasło jest nieprawidłowe.')
  await page.getByLabel('Obecne hasło', { exact: true }).fill(testPassword)
  await submit.click()
  await expect(page.getByText('Hasło zostało zmienione.', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Obecne hasło', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Nowe hasło', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Wyloguj', exact: true }).click()
  await expect(page).toHaveURL('/login')
  await signIn(page, account)
  await expect(page.getByRole('alert')).toHaveText('Nieprawidłowy adres e-mail lub hasło.')
  await signIn(page, { ...account, password: 'Updated-test-only-2026' })
  await expect(page).toHaveURL('/')
  await openProfile(page)
  await expect(page.getByLabel('Obecne hasło', { exact: true })).toBeVisible()
})

test('keeps weight details collapsed and draws a chart only from the second measurement', async ({ app, page }) => {
  await page.clock.setFixedTime(new Date('2026-11-14T09:00:00.000Z'))
  await app.open('/profile')
  await expandProfileSection(page, 'Masa ciała')
  await page.getByRole('link', { name: 'Włącz zapisywanie masy ciała', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Mam ukończone 18 lat.', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Zgadzam się na zapisywanie mojej masy ciała i kategorii wagowej na moim koncie.', exact: true }).check()
  await page.getByRole('button', { name: 'Włącz', exact: true }).click()
  await expect.poll(async () => (await app.readProfile())?.healthDataConsent).toMatchObject({ adultConfirmed: true })
  await app.seedBodyWeight({ date: '2026-11-13', weightKg: 78.4, createdAt: '2026-11-13T09:00:00.000Z', updatedAt: '2026-11-13T09:00:00.000Z' })
  const weight = page.getByRole('region', { name: 'Masa ciała', exact: true })
  await expect(weight.getByRole('button').first()).toContainText('78,4 kg · średnia z 7 dni')
  await expect(weight.getByRole('button').first()).toHaveAttribute('aria-expanded', 'false')
  await expect(weight.getByRole('img')).toHaveCount(0)
  await expandProfileSection(page, 'Masa ciała')
  await expect(weight.getByText('Wykres pojawi się po 2 pomiarach', { exact: true })).toBeVisible()
  await expect(weight.getByRole('img')).toHaveCount(0)
  await expect(page.getByText('Eksport może zawierać dane o zdrowiu (masa ciała, samopoczucie). Przechowuj go bezpiecznie.', { exact: true })).toBeVisible()
  await app.seedBodyWeight({ date: '2026-11-12', weightKg: 78.6, createdAt: '2026-11-12T09:00:00.000Z', updatedAt: '2026-11-12T09:00:00.000Z' })
  await expect(weight.getByRole('img')).toBeVisible()
})

test('shows Google as the sign-in method and omits password changes for a Google-only account', async ({ page }) => {
  await page.goto('/login')
  const opened = page.waitForEvent('popup')
  await page.getByRole('button', { name: 'Kontynuuj z Google', exact: true }).click()
  await signInWithFakeGoogle(await opened, uniqueEmail())
  await openProfile(page)
  await expect(page.locator('header')).toContainText('Google')
  await expect(page.getByText('Logujesz się przez Google', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Obecne hasło', { exact: true })).toHaveCount(0)
})
