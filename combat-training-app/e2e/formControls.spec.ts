import AxeBuilder from '@axe-core/playwright'
import { test, expect } from './fixtures'

for (const theme of ['dark', 'light'] as const) {
  test(`operates shared controls by keyboard with preserved semantics in ${theme}`, async ({ app, page }) => {
    await app.open('/profile/consent')
    await app.setTheme(theme)
    const adult = page.getByRole('switch', { name: 'Mam ukończone 18 lat.', exact: true })
    const agree = page.getByRole('switch', { name: /^Zgadzam się na zapisywanie/ })
    const enable = page.getByRole('button', { name: 'Włącz', exact: true })
    await expect(adult).not.toBeChecked()
    await expect(agree).not.toBeChecked()
    const track = adult.locator('..').locator('.switch-track')
    await expect(track).toHaveCSS('width', '48px')
    await expect(track).toHaveCSS('height', '28px')
    await expect(enable).toBeDisabled()
    await adult.focus(); await adult.press('Space')
    await expect(adult).toBeChecked()
    await expect(track).toHaveCSS('background-image', /linear-gradient/)
    await expect(enable).toBeDisabled()
    await page.keyboard.press('Tab')
    await expect(agree).toBeFocused()
    await agree.press('Space')
    await expect(enable).toBeEnabled()
    await agree.press('Space')
    await expect(enable).toBeDisabled()
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) => impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])

    await app.open('/exercises')
    const archived = page.getByRole('button', { name: 'Zarchiwizowane', exact: true })
    await expect(archived).toHaveAttribute('aria-expanded', 'false')
    const content = page.locator(`[id="${await archived.getAttribute('aria-controls')}"]`)
    await expect(content).toBeHidden()
    await archived.focus(); await archived.press('Enter')
    await expect(archived).toHaveAttribute('aria-expanded', 'true')
    await expect(content).toBeVisible()
    await archived.press('Space')
    await expect(content).toBeHidden()
    await page.getByRole('button', { name: 'Nowe ćwiczenie', exact: true }).click()
    const boxing = page.getByRole('checkbox', { name: 'Boks', exact: true })
    const face = boxing.locator('..').locator('.multi-chip-face')
    await expect(boxing).toBeChecked()
    const selectedBackground = await face.evaluate((element) => getComputedStyle(element).backgroundColor)
    await boxing.focus(); await boxing.press('Space')
    await expect(boxing).not.toBeChecked()
    await expect(face).not.toHaveCSS('background-color', selectedBackground)
    await boxing.press('Space')
    await expect(boxing).toBeChecked()
    await expect(face).toHaveCSS('background-color', selectedBackground)
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) => impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
