import { block, roundsExercise, workoutPlan } from '../src/test/workoutBuilders'
import { test, expect } from './fixtures'
import AxeBuilder from '@axe-core/playwright'

const time = Date.parse('2026-11-08T10:00:00.000Z')
test.use({ screenshot: 'off' })

test('recovers the same round after reload and redirects home to its running timer', async ({ app, page }) => {
  await app.open('/')
  const plan = workoutPlan([block('bag', [roundsExercise('jab', 3, 120, 30)], 'bag')])
  await app.seedPlan(plan)
  await app.open(`/workouts/${plan.id}`)
  await app.openPlayer()
  await page.clock.setFixedTime(new Date(time))
  await app.startWorkout()
  await page.clock.setFixedTime(new Date(time + 190_000))
  await expect(page.getByText('Runda 2 z 3', { exact: true })).toBeVisible()
  await expect(page.getByText('Pozostały czas: 1 minuta i 20 sekund', { exact: true })).toBeAttached()
  await page.reload()
  await expect(page.getByText('Runda 2 z 3', { exact: true })).toBeVisible()
  await page.goto('about:blank')
  await page.clock.setFixedTime(new Date(time + 230_000))
  await page.goto('/')
  await expect(page).toHaveURL(new RegExp(`/workouts/${plan.id}/active$`))
  await expect(page.getByText('Runda 2 z 3', { exact: true })).toBeVisible()
  await expect(page.getByText('Pozostały czas: 40 sekund', { exact: true })).toBeAttached()
  await page.getByRole('button', { name: 'Dźwięk wyłączony — stuknij, aby włączyć', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Dźwięk wyłączony — stuknij, aby włączyć', exact: true })).toHaveCount(0)
})

test('offers a partial session at last activity after a long absence and saves it to history', async ({ app, page }) => {
  await app.open('/')
  const plan = workoutPlan([block('bag', [roundsExercise('jab', 3, 120, 30)], 'bag')])
  await app.seedPlan(plan)
  await app.open(`/workouts/${plan.id}`)
  await app.openPlayer()
  await page.clock.setFixedTime(new Date(time))
  await app.startWorkout()
  await page.clock.setFixedTime(new Date(time + 190_000))
  await expect(page.getByText('Runda 2 z 3', { exact: true })).toBeVisible()
  await page.goto('about:blank')
  await page.clock.setFixedTime(new Date(time + 600_000))
  await page.goto('/')
  const dialog = page.getByRole('dialog', { name: 'Niedokończony trening', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText(plan.nameSnapshot, { exact: true })).toBeVisible()
  await expect(dialog.locator('time')).toHaveAttribute('datetime', '2026-11-08T10:03:10.000Z')
  const save = dialog.getByRole('button', { name: 'Zapisz to, co zrobione', exact: true })
  await expect(save).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Porzuć', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(save).toBeFocused()
  for (const theme of ['dark', 'light']) {
    await page.evaluate((value) => document.documentElement.dataset.theme = value, theme)
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) =>
      impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])
  }
  await dialog.getByRole('button', { name: 'Zapisz to, co zrobione', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Historia treningów', exact: true }).getByText('Częściowy', { exact: true })).toBeVisible()
  await expect.poll(async () => (await app.readSessions()).length).toBe(1)
  expect((await app.readSessions())[0]).toMatchObject({ status: 'partial', durationSeconds: 190, workSeconds: 120, completedAt: '2026-11-08T10:03:10.000Z' })
  await page.goto('/')
  await expect(page).toHaveURL(/\/$/)
})

