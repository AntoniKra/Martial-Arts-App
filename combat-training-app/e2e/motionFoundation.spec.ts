import AxeBuilder from '@axe-core/playwright'
import type { Page } from '@playwright/test'
import { test, expect } from './fixtures'
import { manualWorkoutSession } from '../src/test/manualWorkoutBuilder'
import { generateScheduledWeek } from '../src/domain/week-plan/scheduledWeek'

const instant = '2026-11-18T12:00:00.000Z', current = '2026-11-16'

async function accessible(page: Page) {
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) => impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])
}

test.beforeEach(async ({ page }) => { await page.clock.setFixedTime(new Date(instant)) })

for (const reducedMotion of ['reduce', 'no-preference'] as const) {
  test(`switches complete palettes without transient text contrast loss with ${reducedMotion}`, async ({ app, page }) => {
    await page.emulateMedia({ reducedMotion })
    await app.open(`/progress/week/${current}`)
    const card = page.getByRole('button', { name: /^Stały tydzień/ })
    for (const theme of ['light', 'dark'] as const) {
      await app.setTheme(theme)
      expect(await card.evaluate((element) => getComputedStyle(element).backgroundColor)).toBe(theme === 'light' ? 'rgb(255, 255, 255)' : 'rgb(23, 23, 25)')
      await accessible(page)
    }
  })

  for (const theme of ['dark', 'light'] as const) {
    test(`switches chart range without entry motion, announces it and respects ${reducedMotion} in ${theme}`, async ({ app, page }) => {
      await page.emulateMedia({ reducedMotion })
      await app.open('/progress'); await app.setTheme(theme)
      for (let index = 0; index < 6; index++) await app.seedSession(manualWorkoutSession({ id: `old-${index}`, workoutDate: '2026-08-31' }))
      await app.seedSession(manualWorkoutSession({ id: 'current', workoutDate: current }))
      const chart = page.getByRole('region', { name: 'Ostatnie tygodnie', exact: true })
      await expect(chart.getByRole('link')).toHaveCount(5)
      const bar = chart.locator('.is-current .progress-week-bar')
      await expect(bar).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
      await expect(bar).toHaveCSS('transition-duration', '0s')
      expect(await chart.evaluate((element) => element.getAnimations({ subtree: true }).length)).toBe(0)
      await expect(chart.locator('[aria-live="polite"]')).toBeEmpty()
      const values = await chart.locator('.is-recent .h-5').allTextContents()
      await chart.getByRole('button', { name: 'Pokaż 12 tygodni', exact: true }).click()
      await expect(chart.getByRole('link')).toHaveCount(12)
      await expect(chart.locator('[aria-live="polite"]')).toHaveText('Pokazano 12 tygodni')
      await expect(bar).toHaveCSS('transform', 'matrix(1, 0, 0, 0.166667, 0, 0)')
      await expect(bar).toHaveCSS('transition-duration', reducedMotion === 'reduce' ? '0s' : '0.3s')
      const older = chart.locator('.is-older').first()
      await expect(older).toHaveCSS('transition-property', reducedMotion === 'reduce' ? 'all' : 'opacity')
      await expect(older).toHaveCSS('transition-delay', '0s')
      await expect(older).toHaveCSS('opacity', '1')
      await chart.getByRole('button', { name: 'Pokaż mniej', exact: true }).click()
      await expect(chart.getByRole('link')).toHaveCount(5)
      await expect(chart.locator('[aria-live="polite"]')).toHaveText('Pokazano 5 tygodni')
      await expect(bar).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
      expect(await chart.locator('.is-recent .h-5').allTextContents()).toEqual(values)
      await accessible(page)
      // Navigating back creates a ready chart again, even after an earlier toggle.
      await app.open('/profile'); await app.open('/progress')
      await expect(chart.getByRole('link')).toHaveCount(5)
      await expect(bar).toHaveCSS('transition-duration', '0s')
    })

    test(`keeps Plan status changes immediate or brief and accessible with ${reducedMotion} in ${theme}`, async ({ app, page }) => {
      await page.emulateMedia({ reducedMotion })
      await app.open(`/progress/week/${current}`); await app.setTheme(theme)
      const plan = generateScheduledWeek(current, { id: 'default', items: [{ id: 'club', day: 2, kind: 'club', disciplineKey: 'boxing', startTime: '18:00', endTime: '19:00', parts: ['technique'], clubName: null }], createdAt: instant, updatedAt: instant }, new Date(instant))
      await app.seedWeekPlan(plan)
      const row = page.getByRole('listitem', { name: 'Środa 2026-11-18', exact: true })
      const badge = row.locator('.status-badge')
      await expect(badge).toHaveText('Plan')
      await app.open(`/progress/week/${current}`)
      await expect(badge).toHaveText('Plan')
      await expect(badge).toHaveCSS('animation-name', 'none')
      await row.getByRole('button', { name: 'Opcje: Boks', exact: true }).click()
      await row.getByRole('button', { name: 'Nie byłem', exact: true }).click()
      await expect(badge).toHaveText('– Nie byłem')
      await expect(badge).toHaveClass(/motion-status-change/)
      await expect(badge).toHaveCSS('animation-name', reducedMotion === 'reduce' ? 'none' : 'motion-status-change')
      await expect.poll(async () => (await app.readWeekPlans())[0]?.schedule?.[0]?.omitted).toBe(true)
      await row.getByRole('button', { name: 'Opcje: Boks', exact: true }).click()
      await row.getByRole('button', { name: 'Przywróć', exact: true }).click()
      await expect(badge).toHaveText('Plan')
      await expect.poll(async () => (await app.readWeekPlans())[0]?.schedule?.[0]?.omitted).toBe(false)
      await app.seedSession(manualWorkoutSession({ id: 'done', workoutDate: '2026-11-18', category: 'technique', parts: ['technique'] }))
      await expect(badge).toHaveText('✓ Zaliczone')
      await accessible(page)
      await app.open('/progress')
      const day = page.getByRole('img', { name: 'czwartek: wolne', exact: true })
      await expect(day).toHaveCSS('animation-name', 'none')
      await app.seedSession(manualWorkoutSession({ id: 'thursday', workoutDate: '2026-11-19' }))
      const done = page.getByRole('img', { name: 'czwartek: wykonany', exact: true })
      await expect(done).toHaveClass(/motion-status-change/)
      await expect(done).toHaveCSS('animation-name', reducedMotion === 'reduce' ? 'none' : 'motion-status-change')
      await accessible(page)
    })
  }

  test(`preserves keyboard controls, press feedback and disclosure focus with ${reducedMotion}`, async ({ app, page }) => {
    await page.emulateMedia({ reducedMotion })
    await app.open('/exercises')
    const disclosure = page.getByRole('button', { name: 'Zarchiwizowane', exact: true })
    const content = page.locator(`[id="${await disclosure.getAttribute('aria-controls')}"]`)
    await disclosure.focus(); await disclosure.press('Enter')
    await expect(content).toBeVisible()
    await expect(disclosure).toBeFocused()
    await expect(content).toHaveCSS('animation-name', reducedMotion === 'reduce' ? 'none' : 'motion-disclose')
    await expect(disclosure.locator('.disclosure-chevron')).toHaveCSS('transform', reducedMotion === 'reduce' ? 'none' : 'matrix(-1, 0, 0, -1, 0, 0)')
    await disclosure.press('Space'); await expect(content).toBeHidden()
    const primary = page.getByRole('button', { name: 'Nowe ćwiczenie', exact: true })
    await primary.scrollIntoViewIfNeeded()
    await primary.hover(); await page.mouse.down()
    await expect(primary).toHaveCSS('transform', reducedMotion === 'reduce' ? 'none' : 'matrix(0.98, 0, 0, 0.98, 0, 0)')
    await page.mouse.up()
    const boxing = page.getByRole('checkbox', { name: 'Boks', exact: true })
    await expect(boxing).toBeChecked()
    await boxing.focus(); await boxing.press('Space'); await expect(boxing).not.toBeChecked()
    await boxing.press('Space'); await expect(boxing).toBeChecked()
    await expect(boxing.locator('..').locator('.multi-chip-face')).toHaveCSS('transition-duration', reducedMotion === 'reduce' ? '0.1s, 0.1s, 0.1s' : '0.1s, 0.1s, 0.1s, 0.1s')
    await app.open('/profile/consent')
    const adult = page.getByRole('switch', { name: 'Mam ukończone 18 lat.', exact: true })
    await adult.focus(); await adult.press('Space'); await expect(adult).toBeChecked()
    await expect(adult.locator('..').locator('.switch-track')).toHaveCSS('width', '48px')
    await expect(page.getByRole('button', { name: 'Włącz', exact: true })).toBeDisabled()
    await accessible(page)
    await app.open('/workout-sessions/new')
    const radio = page.getByRole('radio', { name: 'Boks', exact: true })
    await radio.focus(); await radio.press('ArrowRight')
    await expect(page.getByRole('radio', { name: 'Kickboxing', exact: true })).toBeChecked()
    const face = page.getByRole('radio', { name: 'Kickboxing', exact: true }).locator('..').locator('.choice-face')
    await expect(face.locator('.choice-check')).toBeVisible()
    await face.locator('..').hover(); await page.mouse.down()
    await expect(face).toHaveCSS('transform', reducedMotion === 'reduce' ? 'none' : 'matrix(0.98, 0, 0, 0.98, 0, 0)')
    await page.mouse.up()
    await app.open('/')
    // Start swaps the quick start card for the empty state once data loads; press the settled link.
    await expect(page.getByRole('heading', { name: 'Zacznij swój pierwszy trening', exact: true })).toBeVisible()
    const start = page.getByRole('link', { name: 'Utwórz plan', exact: true })
    await start.hover(); await page.mouse.down()
    await expect(start).toHaveCSS('transform', reducedMotion === 'reduce' ? 'none' : 'matrix(0.985, 0, 0, 0.985, 0, 0)')
    await page.mouse.move(0, 0); await page.mouse.up()
  })
}
