test('history filters collapse, count active choices, filter results and clear without losing search', async ({ app, page }) => {
  await app.open('/workouts?tab=history')
  await app.seedSession(workoutSession({ id: 'boxing', workoutPlanNameSnapshot: 'Trening boks', stepResults: [sessionStep()] }))
  await app.seedSession(workoutSession({ id: 'thai', workoutPlanNameSnapshot: 'Trening thai', disciplineKey: 'muay_thai', stepResults: [sessionStep()] }))
  await expect(page.getByRole('article')).toHaveCount(2)
  const toggle = page.getByRole('button', { name: 'Filtry', exact: true })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('combobox', { name: 'Sortowanie' })).toBeHidden()
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  const disciplines = page.getByRole('group', { name: 'Dyscyplina', exact: true })
  await disciplines.getByRole('button', { name: 'Muay Thai', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Filtry/ })).toContainText('1')
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toContainText('Trening thai')
  await page.getByRole('combobox', { name: 'Sortowanie' }).selectOption('oldest')
  const activeToggle = page.getByRole('button', { name: /^Filtry/ })
  await expect(activeToggle).toContainText('2')
  await activeToggle.click()
  await expect(activeToggle).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('searchbox', { name: 'Szukaj treningu' }).fill('Trening')
  await activeToggle.click()
  await expect(disciplines.getByRole('button', { name: 'Muay Thai', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Wyczyść filtry' }).click()
  await expect(toggle).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(2)
  await expect(page.getByRole('searchbox')).toHaveValue('Trening')
  const strip = disciplines.locator('div').first()
  expect(await strip.evaluate((element) => getComputedStyle(element).scrollSnapType)).toBe('x mandatory')
  // Only narrow screens need to scroll; on tablet and desktop every discipline fits.
  if ((page.viewportSize()?.width ?? 0) < 480) expect(await strip.evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(true)
  for (const theme of ['light', 'dark'] as const) {
    await app.setTheme(theme)
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) => impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.getByRole('link', { name: 'Dodaj trening spoza aplikacji', exact: true }).click()
  await expect(page.getByRole('form', { name: 'Trening spoza aplikacji' })).toBeVisible()
})

