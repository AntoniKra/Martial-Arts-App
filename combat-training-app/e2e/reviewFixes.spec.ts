test('RPE has no initial choice, supports touch drag, snaps to six and saves it', async ({ app, page, context }) => {
  await app.open('/workouts?tab=history')
  const session = workoutSession({ stepResults: [sessionStep()] })
  await app.seedSession(session)
  await app.open(`/workout-sessions/${session.id}/feedback`)
  await page.getByRole('button', { name: 'Oceń teraz', exact: true }).click()
  const slider = page.getByRole('slider', { name: sliderName, exact: true })
  await expect(slider).toHaveAttribute('aria-valuetext', 'Nie wybrano RPE')
  await expect(page.getByRole('button', { name: 'Zapisz RPE', exact: true })).toBeDisabled()
  await slider.scrollIntoViewIfNeeded()
  const bounds = await slider.boundingBox()
  if (!bounds) throw new Error('RPE slider is not visible')
  expect(bounds.height).toBeGreaterThanOrEqual(56)
  const touch = await context.newCDPSession(page)
  const y = bounds.y + bounds.height / 2
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: bounds.x + bounds.width / 22, y }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: bounds.x + bounds.width * 6.5 / 11, y }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(slider).toHaveAttribute('aria-valuenow', '6')
  await expect(slider).toHaveAttribute('aria-valuetext', '6 · Między ciężko a bardzo ciężko')
  await page.getByRole('button', { name: 'Zapisz RPE 6', exact: true }).click()
  await expect(page.getByText('Zapisano RPE 6', { exact: true })).toBeVisible()
  await expect.poll(async () => (await app.readSessions())[0]?.rpe).toBe(6)
})

test('RPE step buttons start at five and the keyboard reaches both endpoints', async ({ app, page }) => {
  await app.open('/workout-sessions/new')
  const slider = page.getByRole('slider', { name: sliderName, exact: true })
  await expect(slider).toHaveAttribute('aria-valuetext', 'Nie wybrano RPE')
  await page.getByRole('button', { name: 'Mniej', exact: true }).click()
  await expect(slider).toHaveAttribute('aria-valuenow', '5')
  await page.getByRole('button', { name: 'Więcej', exact: true }).click()
  await expect(slider).toHaveAttribute('aria-valuenow', '6')
  await slider.press('End'); await slider.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '10')
  await slider.press('Home'); await slider.press('ArrowDown')
  await expect(slider).toHaveAttribute('aria-valuenow', '0')
  await expect(slider).toBeFocused()
  await slider.click({ position: { x: 1, y: 20 } })
  await expect(slider).toHaveAttribute('aria-valuenow', '0')
  for (const theme of ['light', 'dark'] as const) {
    await app.setTheme(theme)
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(({ impact }) => impact && ['moderate', 'serious', 'critical'].includes(impact))).toEqual([])
  }
  await app.open('/workout-sessions/new')
  await page.getByRole('button', { name: 'Więcej', exact: true }).click()
  await expect(slider).toHaveAttribute('aria-valuenow', '5')
})

test('custom minutes replace Other, remember its placeholder and save with aligned date shortcuts', async ({ app, page }) => {
  await app.open('/workout-sessions/new')
  const form = page.getByRole('form', { name: 'Trening spoza aplikacji', exact: true })
  const dateBox = await form.getByLabel('Data', { exact: true }).boundingBox()
  for (const name of ['Dziś', 'Wczoraj']) {
    const shortcut = await form.getByRole('button', { name, exact: true }).boundingBox()
    expect(shortcut?.height).toBe(dateBox?.height)
    expect(shortcut?.y).toBe(dateBox?.y)
  }
  await form.getByRole('radio', { name: 'Boks', exact: true }).check()
  await form.getByRole('checkbox', { name: /^Worek/ }).check()
  const other = form.getByRole('radio', { name: 'Inny', exact: true })
  const bounds = await other.locator('..').boundingBox()
  const documentY = (bounds?.y ?? 0) + await page.evaluate(() => scrollY)
  await other.click()
  const minutes = form.getByRole('spinbutton', { name: 'Czas w minutach', exact: true })
  await expect(minutes).toBeFocused()
  await expect(minutes).toHaveAttribute('placeholder', 'np. 75')
  const inputBounds = await minutes.boundingBox()
  expect(inputBounds?.x).toBe(bounds?.x)
  expect(inputBounds?.width).toBe(bounds?.width)
  expect((inputBounds?.y ?? 0) + await page.evaluate(() => scrollY)).toBe(documentY)
  await expect(other).toHaveCount(0)
  await minutes.fill('75')
  await form.getByRole('radio', { name: '60 min', exact: true }).check()
  await other.click()
  await expect(minutes).toBeFocused()
  await expect(minutes).toHaveValue('')
  await expect(minutes).toHaveAttribute('placeholder', '75')
  await minutes.fill('75')
  await form.getByRole('button', { name: 'Zapisz', exact: true }).click()
  await expect(form.getByRole('slider', { name: sliderName })).toBeFocused()
  await expect(form.getByRole('slider')).toHaveAttribute('aria-valuetext', 'Nie wybrano RPE')
  await selectRpe(form, 7)
  await form.getByRole('button', { name: 'Zapisz', exact: true }).click()
  await expect(page).toHaveURL(/\/workouts\?tab=history$/)
  await expect.poll(async () => (await app.readSessions())[0]?.durationSeconds).toBe(4500)
})
