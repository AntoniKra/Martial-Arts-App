async function fullyInsideStrip(button: Locator) {
  await expect.poll(async () => {
    const bounds = await button.boundingBox(), strip = await button.locator('..').boundingBox()
    return bounds && strip ? bounds.x >= strip.x && bounds.x + bounds.width <= strip.x + strip.width + 1 : false
  }).toBe(true)
}

test('opens filters with the full first tile and reveals the selected tile again', async ({ app, page }) => {
  await app.open('/workouts')
  const toggle = page.getByRole('button', { name: /^Filtry/ })
  await toggle.click()
  const disciplines = page.getByRole('group', { name: 'Dyscyplina', exact: true })
  const first = disciplines.getByRole('button', { name: 'Wszystkie', exact: true })
  await fullyInsideStrip(first)
  const strip = first.locator('..')
  await expect(strip).toHaveCSS('scrollbar-width', 'none')
  expect(await strip.evaluate((element) => getComputedStyle(element, '::-webkit-scrollbar').display)).toBe('none')
  const last = disciplines.getByRole('button').last()
  await last.click()
  await fullyInsideStrip(last)
  await strip.evaluate((element) => { element.scrollLeft = 0 })
  await toggle.click()
  await toggle.click()
  await fullyInsideStrip(last)
  await page.getByRole('button', { name: 'Wyczyść filtry', exact: true }).click()
  await fullyInsideStrip(first)
})

test('collapses password and data controls independently while keeping account controls visible', async ({ app, page }) => {
  await app.open('/profile')
  const password = page.getByRole('button', { name: 'Zmień hasło', exact: true })
  const data = page.getByRole('button', { name: 'Pobierz swoje dane', exact: true })
  const current = page.getByLabel('Obecne hasło', { exact: true })
  const exports = page.getByRole('region', { name: 'Twoje dane', exact: true })
  for (const toggle of [password, data]) await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(current).toBeHidden()
  await expect(exports.getByRole('button')).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Konto', exact: true })).toContainText('@')
  await expect(page.getByRole('button', { name: 'Wyloguj', exact: true })).toBeVisible()
  await password.click()
  await expect(password).toHaveAttribute('aria-expanded', 'true')
  await expect(current).toBeVisible()
  await expect(page.getByLabel('Nowe hasło', { exact: true })).toBeVisible()
  await data.click()
  await expect(data).toHaveAttribute('aria-expanded', 'true')
  await expect(exports.getByRole('button')).toHaveCount(5)
  await expect(exports).toContainText('Możesz pobrać wszystko')
  await password.click()
  await expect(current).toBeHidden()
  await expect(data).toHaveAttribute('aria-expanded', 'true')
  await data.click()
  await expect(data).toHaveAttribute('aria-expanded', 'false')
  await expect(exports.getByRole('button')).toHaveCount(1)
})

test('uses centered keyboard-accessible tiles, empty custom minutes and distinct RPE nine', async ({ app, page }) => {
  await app.open('/workout-sessions/new')
  const form = page.getByRole('form', { name: 'Trening spoza aplikacji', exact: true })
  const boxing = form.getByRole('radio', { name: 'Boks', exact: true })
  await boxing.check()
  await expect(boxing.locator('..')).toContainText('✓')
  await expect(boxing.locator('..')).toHaveCSS('justify-content', 'center')
  await expect(boxing.locator('..')).toHaveCSS('font-weight', '600')
  await boxing.press('ArrowRight')
  await expect(form.getByRole('radio', { name: 'Kickboxing', exact: true })).toBeChecked()
  const duration = form.getByRole('radio', { name: '60 min', exact: true })
  await duration.check()
  await expect(duration.locator('..')).toContainText('✓')
  await duration.press('ArrowRight')
  await expect(form.getByRole('radio', { name: '90 min', exact: true })).toBeChecked()
  await form.getByRole('radio', { name: 'Inny', exact: true }).click()
  const minutes = form.getByRole('spinbutton', { name: 'Czas w minutach', exact: true })
  await expect(minutes).toBeFocused()
  await expect(minutes).toHaveValue('')
  await expect(minutes).not.toHaveAttribute('placeholder')
  await expect(minutes).toHaveCSS('text-align', 'center')
  await expect(minutes.locator('..')).toHaveText('min')
  await minutes.fill('480')
  const fieldBounds = await minutes.boundingBox(), suffixBounds = await minutes.locator('..').locator('span').boundingBox()
  expect(fieldBounds).not.toBeNull()
  expect(suffixBounds).not.toBeNull()
  expect(suffixBounds!.x + suffixBounds!.width).toBeLessThanOrEqual(fieldBounds!.x + fieldBounds!.width)
  await minutes.fill('75')
  await form.getByRole('checkbox', { name: /^Worek/ }).check()
  await selectRpe(form, 8)
  await expect(form.getByRole('slider')).toHaveAttribute('aria-valuetext', '8 · Między bardzo ciężko a maksymalnie')
  await form.getByRole('button', { name: 'Więcej', exact: true }).click()
  await expect(form.getByRole('slider')).toHaveAttribute('aria-valuetext', '9 · Prawie maksymalnie')
  await expect(form.getByText(/Wybierz pole lub przeciągnij/)).toHaveCount(0)
  await form.getByRole('button', { name: 'Zapisz', exact: true }).click()
  await expect(page).toHaveURL(/\/workouts\?tab=history$/)
  await expect.poll(async () => (await app.readSessions())[0]).toMatchObject({ durationSeconds: 4500, rpe: 9, disciplineKey: 'kickboxing' })
})

